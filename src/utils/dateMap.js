export const dayMap = (code) => {
    if (code === 0) return "Sunday";
    if (code === 1) return "Monday";
    if (code === 2) return "Tuesday";
    if (code === 3) return "Wednesday";
    if (code === 4) return "Thursday";
    if (code === 5) return "Friday";
    if (code === 6) return "Saturday";
}

export const monthMap = (code) => {
    if (code === 0) return "January";
    if (code === 1) return "February";
    if (code === 2) return "March";
    if (code === 3) return "April";
    if (code === 4) return "May";
    if (code === 5) return "June";
    if (code === 6) return "July";
    if (code === 7) return "August";
    if (code === 8) return "September";
    if (code === 9) return "October";
    if (code === 10) return "November";
    if (code === 11) return "December";
}